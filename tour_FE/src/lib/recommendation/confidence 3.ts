/**
 * 아는 게 적은 섬을 낮게 주지 않는다.
 *
 * 시설·종목 데이터가 적다고 그 섬이 별로인 건 아니다. 수집 범위가 거기까지
 * 안 미쳤을 뿐일 수 있다(시설 데이터 주석: "웹 조사 1·2구역"). 실제로 연평도·
 * 교동도는 종목 0종, 시설 2~3곳인데 서해 최북단이라 조사에서 빠졌을 가능성이 크다.
 *
 * 그대로 두면 "우리가 조사를 덜 한 섬"이 "추천되지 않는 섬"으로 굳는다.
 * 근거가 얇을수록 점수를 중립(50)쪽으로 당겨, 조사 격차가 추천 격차가 되지 않게 한다.
 *
 * 반대로 근거가 하나뿐인데 높은 점수가 나온 경우도 같이 눌린다. 이것도 맞는 방향이다
 * — 데이터 한 건으로 그 섬을 확신할 수는 없다.
 */

const NEUTRAL = 50;

/**
 * 이 개수쯤 자료가 있으면 신호를 그대로 믿는다.
 *
 * 3으로 정한 근거 (140개 조건 조합 측정):
 *   보정없음 → 등장 12개 섬, 연평도·소야도는 0회
 *   3        → 등장 12개 섬, 연평도·소야도 등장
 *   4        → 등장 11개 섬
 *   6        → 등장 10개 섬 (얇은 데이터로 가끔 이기던 섬까지 눌린다)
 * 더 올리면 자료 적은 섬이 중립에 묶여 아예 못 이기고, 더 내리면 자료 한두 건으로
 * 순위가 흔들린다.
 */
const CONFIDENCE_FULL_AT = 3;

export function applyConfidence(score: number, knownItemCount: number): number {
  const confidence = Math.min(knownItemCount / CONFIDENCE_FULL_AT, 1);
  return Math.round(NEUTRAL + (score - NEUTRAL) * confidence);
}
